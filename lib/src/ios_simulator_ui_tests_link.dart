import 'dart:io';

import 'package:path/path.dart' as p;

const _marker = '// [mplatrol-e2e] RunnerUITests links Flutter.framework for simulator builds';

/// Makes local iOS simulator builds of `RunnerUITests` link.
///
/// `RunnerUITests` (`inherit! :complete` in the Podfile) links the plugins'
/// static objects, such as the firebase_core/analytics/performance pigeon
/// codecs, which reference `FlutterStandardMessageCodec` and other
/// Flutter.framework symbols. Nothing links Flutter.framework into the UI-test
/// bundle for a Debug simulator build, so it fails with undefined
/// `_OBJC_CLASS_$_FlutterStandard*` symbols; with explicit modules on it fails
/// earlier with `'Flutter/Flutter.h' not found` from patrol.framework.
///
/// Patches the target's Pods xcconfig (regenerated by every `pod install`) to
/// add `-framework Flutter` and the simulator slice of Flutter.xcframework to
/// that target only, for the simulator SDK only, and to build it with implicit
/// modules. Returns whether the file changed; false when already patched or
/// when the xcconfig or `FLUTTER_ROOT` is missing.
bool linkFlutterIntoSimulatorUiTests(String repo) {
  final xcconfig = File(p.join(repo, 'ios', 'Pods', 'Target Support Files', 'Pods-Runner-RunnerUITests',
      'Pods-Runner-RunnerUITests.debug.xcconfig'));
  final flutterRoot = _flutterRoot(repo);
  if (!xcconfig.existsSync() || flutterRoot == null) {
    return false;
  }
  final content = xcconfig.readAsStringSync();
  if (content.contains(_marker)) {
    return false;
  }
  final framework = p.join(
      flutterRoot, 'bin', 'cache', 'artifacts', 'engine', 'ios', 'Flutter.xcframework', 'ios-arm64_x86_64-simulator');
  final patched = [
    ..._appendTo(content, 'OTHER_LDFLAGS', r'$(MPLATROL_SIM_FLUTTER_LDFLAGS)'),
    '',
    _marker,
    // A `[sdk=...]` override of OTHER_LDFLAGS itself would replace the Pods'
    // flags for that SDK; these variables are empty except on the simulator.
    'MPLATROL_SIM_FLUTTER_LDFLAGS[sdk=iphonesimulator*] = -framework Flutter',
    'MPLATROL_SIM_FLUTTER_FRAMEWORKS[sdk=iphonesimulator*] = "$framework"',
    'SWIFT_ENABLE_EXPLICIT_MODULES = NO',
    'CLANG_ENABLE_EXPLICIT_MODULES = NO',
    '',
  ];
  xcconfig.writeAsStringSync(
      _appendTo(patched.join('\n'), 'FRAMEWORK_SEARCH_PATHS', r'$(MPLATROL_SIM_FLUTTER_FRAMEWORKS)').join('\n'));
  return true;
}

/// [content]'s lines with [value] appended to the `<setting> = ...` line, or
/// a new `<setting> = $(inherited) <value>` line when there is none.
List<String> _appendTo(String content, String setting, String value) {
  final lines = content.split('\n');
  final index = lines.indexWhere((line) => line.startsWith('$setting = '));
  if (index < 0) {
    return [...lines, '$setting = \$(inherited) $value'];
  }
  lines[index] = '${lines[index].trimRight()} $value';
  return lines;
}

/// `FLUTTER_ROOT` from the `ios/Flutter/Generated.xcconfig` Flutter wrote for this build.
String? _flutterRoot(String repo) {
  final generated = File(p.join(repo, 'ios', 'Flutter', 'Generated.xcconfig'));
  if (!generated.existsSync()) {
    return null;
  }
  for (final line in generated.readAsLinesSync()) {
    if (line.startsWith('FLUTTER_ROOT=')) {
      final root = line.substring('FLUTTER_ROOT='.length).trim();
      return root.isEmpty ? null : root;
    }
  }
  return null;
}
