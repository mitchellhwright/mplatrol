/// Writes a temporary Patrol target for the files selected by [target],
/// [targetRegex], and [sdk].
///
/// Patrol CLI can select one raw target file, but it does not understand the
/// `mplatrol` regex/SDK filters. For those filtered runs the native Android/iOS
/// runners are already generated with the filtered test methods; this helper
/// writes a normal `_test.dart` entrypoint in the Patrol test directory that
/// imports the same selected files. Patrol then generates its own
/// `test_bundle.dart` from that entrypoint.
String retargetPatrolTestBundle(
  String repo, {
  required String? target,
  required String? targetRegex,
  required String? sdk,
  PatrolSelectionPlan? selection,
}) {
  final files = discoverPatrolTestFiles(
    repo,
    target: target,
    targetRegex: targetRegex,
    sdk: sdk,
    selection: selection,
  );
  if (files.isEmpty) {
    throw StateError(
      'No patrolTest() found in ${target ?? patrolTestDirectoryPath(repo)} '
      '${targetRegex == null ? '' : 'matching /$targetRegex/ '}'
      '${sdk == null ? '' : 'for SDK "$sdk" '}— cannot create a filtered '
      'Patrol target.',
    );
  }

  final generatedDirectory = Directory(patrolTestDirectoryPath(repo));
  final filteredTargetPath = p.join(generatedDirectory.path, 'mplatrol_filtered_test.dart');
  final modules = files.map((file) => file.basename).toList();
  final buffer = StringBuffer()
    ..writeln('// Generated by mplatrol; do not edit.')
    ..writeln("import 'package:test/test.dart';")
    ..writeln();
  for (final module in modules) {
    buffer.writeln(
      "import '$module.dart' as $module;",
    );
  }
  buffer
    ..writeln()
    ..writeln('void main() {');
  for (final module in modules) {
    buffer.writeln("  group('$module', () { $module.main(); });");
  }
  buffer.writeln('}');

  File(filteredTargetPath).writeAsStringSync(buffer.toString());
  return p.relative(filteredTargetPath, from: repo).replaceAll('\\', '/');
}

/// The iOS-owned Patrol bundle the LambdaTest and local iOS builds compile,
/// written next to Patrol's shared `test_bundle.dart`. It does not end in
/// `_test.dart`, so Patrol and test discovery never treat it as a test target.
const iosPatrolTestBundleFile = 'mplatrol_ios_test_bundle.dart';

/// Dart VM define the repo-local patched patrol_cli reads as the file name of
/// the bundle it generates and compiles, in place of Patrol's shared
/// `test_bundle.dart`. Local iOS sets it to [iosPatrolTestBundleFile].
const patrolTestBundleDefine = 'MPLATROL_PATROL_TEST_BUNDLE';

/// Repo-relative Patrol targets for local iOS's own bundle: exactly the files
/// the generated iOS runner selects for [target], [targetRegex], and [sdk].
///
/// Passing each file as its own `--target` makes Patrol group it under its
/// basename, the group the generated runner resolves. Local iOS therefore
/// never needs mplatrol's `mplatrol_filtered_test.dart` wrapper, which belongs to a
/// concurrent Android run.
List<String> iosPatrolBundleTargets(
  String repo, {
  required String? target,
  required String? targetRegex,
  required String? sdk,
  Map<String, String>? environment,
}) {
  final testDirectory = patrolTestDirectoryPath(repo);
  return [
    for (final file in discoverPatrolTestFiles(
      repo,
      target: target,
      targetRegex: targetRegex,
      sdk: sdk,
      environment: environment,
    ))
      p.relative(p.join(testDirectory, '${file.basename}.dart'), from: repo).replaceAll('\\', '/'),
  ];
}

/// patrol_cli version whose global activation supplies the bundle generator.
const patrolCliBundlerVersion = '4.8.0';

/// Dart program run against the globally activated patrol_cli that writes
/// Patrol's `test_bundle.dart` for one target under a scratch project root.
const _bundleTemplatroleGenerator = '''
import 'package:file/local.dart';
import 'package:patrol_cli/src/base/logger.dart';
import 'package:patrol_cli/src/test_bundler.dart';

void main(List<String> args) {
  final root = const LocalFileSystem().directory(args[0]);
  TestBundler(projectRoot: root, logger: Logger())
      .createTestBundle('patrol_test', ['patrol_test/\${args[1]}.dart'], null, null);
}
''';

/// Thrown when Patrol's bundle scaffolding cannot be generated; [exitCode] is
/// the `mplatrol` exit code to report.
class PatrolBundleTemplatroleException implements Exception {
  /// Creates the exception with an actionable [message].
  PatrolBundleTemplatroleException(this.message, this.exitCode);

  /// What failed and how to fix it.
  final String message;

  /// `mplatrol` exit code for this failure.
  final int exitCode;
}

/// Generates Patrol's `test_bundle.dart` scaffolding with the installed
/// patrol_cli's own bundler, in a scratch directory, and returns its text.
///
/// A fresh checkout has no `patrol_test/test_bundle.dart` until an Android
/// `patrol build` runs. iOS only needs that file's target-independent
/// PatrolAppService scaffolding (it rewrites the generated import and group
/// regions itself), so it generates the scaffolding here instead of requiring
/// an Android build, and never writes the shared bundle the Android arm owns.
/// [module] is any selected test's basename; its import is replaced later.
Future<String> generatePatrolBundleTemplatrole(String module) async {
  final environment = getDep<PlatformWrapper>().environment;
  final cacheRoot = pubCacheRoot(environment);
  final packageConfig = cacheRoot == null
      ? null
      : File(p.join(cacheRoot, 'global_packages', 'patrol_cli', '.dart_tool', 'package_config.json'));
  if (packageConfig == null || !packageConfig.existsSync()) {
    throw PatrolBundleTemplatroleException(
      'patrol_cli is not globally activated (no ${packageConfig?.path ?? 'pub cache'}), so the '
      'Patrol test bundle cannot be generated. Run `dart pub global activate patrol_cli '
      '$patrolCliBundlerVersion` (or `mplatrol setup-environment`) and retry.',
      ExitCode.config.code,
    );
  }
  final scratch = Directory.systemTemp.createTempSync('mplatrol_patrol_bundle_');
  try {
    Directory(p.join(scratch.path, 'patrol_test')).createSync();
    final generator = File(p.join(scratch.path, 'generate_bundle.dart'))
      ..writeAsStringSync(_bundleTemplatroleGenerator);
    final result = await getDep<MplatrolShell>().runArgs(
      'dart',
      ['run', '--packages=${packageConfig.path}', generator.path, scratch.path, module],
      throwOnError: false,
    );
    final bundle = File(p.join(scratch.path, 'patrol_test', 'test_bundle.dart'));
    if (result.exitCode != 0 || !bundle.existsSync()) {
      throw PatrolBundleTemplatroleException(
        'Generating the Patrol test bundle with patrol_cli '
        '$patrolCliBundlerVersion failed (exit ${result.exitCode}): '
        '${'${result.stderr}'.trim()} Re-activate it with `dart pub global activate '
        'patrol_cli $patrolCliBundlerVersion`.',
        ExitCode.software.code,
      );
    }
    return bundle.readAsStringSync();
  } finally {
    scratch.deleteSync(recursive: true);
  }
}

/// Removes mplatrol's temporary filtered Patrol target when a run is unfiltered.
void removeFilteredPatrolTestTarget(String repo) {
  final file = File(p.join(patrolTestDirectoryPath(repo), 'mplatrol_filtered_test.dart'));
  if (file.existsSync()) {
    file.deleteSync();
  }
}
